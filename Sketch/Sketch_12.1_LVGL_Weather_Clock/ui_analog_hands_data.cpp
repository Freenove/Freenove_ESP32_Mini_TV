static lv_image_dsc_t ui_make_argb8888_dsc(const uint8_t *data, uint32_t data_size,
                                           uint16_t ww, uint16_t hh)
{
    lv_image_dsc_t dsc;
    memset(&dsc, 0, sizeof(dsc));
    dsc.header.magic = LV_IMAGE_HEADER_MAGIC;
    dsc.header.cf = LV_COLOR_FORMAT_ARGB8888;
    dsc.header.flags = 0;
    dsc.header.w = ww;
    dsc.header.h = hh;
    dsc.header.stride = (uint16_t)(ww * 4);
    dsc.data_size = data_size;
    dsc.data = data;
    return dsc;
}

